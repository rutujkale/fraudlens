"""Part 11 external-validation tables, generated from ``results/``.

Reads the CSVs/JSON written by ``scripts/run_external_validation.py`` and injects a
markdown block between the ``external_validation_table`` markers in
``docs/external_validation.md``. No number is typed by hand.

Usage: python scripts/external_validation_report.py
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
DOC = ROOT / "docs" / "external_validation.md"
BEGIN, END = "<!-- BEGIN external_validation_table -->", "<!-- END external_validation_table -->"


def _read(name: str) -> pd.DataFrame:
    return pd.read_csv(RES / name)


def _md(rows: list[list[Any]], header: list[str]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    for r in rows:
        lines.append("| " + " | ".join(_fmt(v) for v in r) + " |")
    return "\n".join(lines)


def _fmt(v: Any) -> str:
    if isinstance(v, float):
        return f"{v:.4f}"
    return str(v)


def build_block() -> str:
    val = _read("external_validation.csv")
    gap = _read("external_gap.csv").iloc[0]
    cal = _read("external_calibration.csv")
    pol = _read("external_policy.csv")
    trunc = _read("external_truncation_check.csv")
    uid = json.loads((RES / "external_uid_stats_ieee_cis.json").read_text(encoding="utf-8"))

    parts = ["<!-- generated by scripts/external_validation_report.py; do not edit by hand -->", ""]

    test = val[val["window"] == "test"]
    parts.append("IEEE-CIS test window (evaluated once):")
    parts.append("")
    parts.append(
        _md(
            [
                [
                    r["model"],
                    r["n"],
                    r["prevalence"],
                    r["pr_auc"],
                    r["roc_auc"],
                    r["brier"],
                    r["ece"],
                    r["lift_at_top_0.01"],
                    r["recall_at_top_0.01"],
                ]
                for _, r in test.iterrows()
            ],
            [
                "model", "n", "prevalence", "PR-AUC", "ROC-AUC", "Brier", "ECE",
                "lift@1%", "recall@1%",
            ],
        )
    )
    parts.append("")
    parts.append("Sim-to-real gap:")
    parts.append("")
    parts.append(
        _md(
            [
                ["primary (R1 - R2 PR-AUC, IEEE test)",
                 gap["primary_gap_pr_auc_r1_minus_r2_on_ieee_test"]],
                ["secondary (dev-val S - IEEE test R2)",
                 gap["secondary_gap_dev_val_minus_ieee_test"]],
                ["R1 IEEE test PR-AUC", gap["r1_ieee_test_pr_auc"]],
                ["R2 IEEE test PR-AUC", gap["r2_ieee_test_pr_auc"]],
                ["R2 dev-val (shared S) PR-AUC", gap["r2_dev_val_shared_subset_pr_auc"]],
            ],
            ["metric", "value"],
        )
    )
    parts.append("")
    parts.append(f"Secondary note: *{gap['secondary_note']}*. {gap['note']}.")
    parts.append("")
    parts.append("Calibration (Brier / ECE):")
    parts.append("")
    parts.append(
        _md(
            [[r["stage"], r["brier"], r["ece"]] for _, r in cal.iterrows()],
            ["stage", "Brier", "ECE"],
        )
    )
    parts.append("")
    parts.append("R5 cost policy (IEEE test):")
    parts.append("")
    parts.append(
        _md(
            [
                [
                    r["policy"],
                    r["realized_cost"],
                    r["pct_saving_vs_approve_all"],
                    r["n_approve"],
                    r["n_stepup"],
                    r["n_review"],
                    r["n_block"],
                    r["n_demoted"],
                ]
                for _, r in pol.iterrows()
            ],
            [
                "policy", "realized cost", "saving vs approve-all %",
                "approve", "step-up", "review", "block", "demoted",
            ],
        )
    )
    parts.append("")
    parts.append("Point-in-time truncation check (adapter + real `build_features`):")
    parts.append("")
    parts.append(
        _md(
            [[int(r["cut_index"]), r["cut"], int(r["n_rows"]), r["max_abs_diff"], r["passed"]]
             for _, r in trunc.iterrows()],
            ["cut", "timestamp", "rows", "max abs diff", "passed"],
        )
    )
    parts.append("")
    uid_note = (
        "`uid` limitations: {n_uids:,} pseudo-customers for {n_transactions:,} rows "
        "(mean {mean:.2f}, p50 {p50:.0f}, p90 {p90:.0f}, p99 {p99:.0f}, max {maxi:,} tx/uid; "
        "{single:.1%} of uids have a single transaction). Device features are NaN wherever "
        "`DeviceInfo` is missing (`device_age_days` NaN share ~0.80) — documented, not hidden."
    )
    parts.append(
        uid_note.format(
            n_uids=uid["n_uids"],
            n_transactions=uid["n_transactions"],
            mean=uid["tx_per_uid_mean"],
            p50=uid["tx_per_uid_p50"],
            p90=uid["tx_per_uid_p90"],
            p99=uid["tx_per_uid_p99"],
            maxi=uid["tx_per_uid_max"],
            single=uid["single_tx_uid_share"],
        )
    )
    parts.append("")
    return "\n".join(parts)


def main() -> None:
    table = build_block()
    text = DOC.read_text(encoding="utf-8")
    pre, rest = text.split(BEGIN, 1)
    _, post = rest.split(END, 1)
    DOC.write_text(f"{pre}{BEGIN}\n{table}{END}{post}", encoding="utf-8")
    print(f"wrote tables into {DOC.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
